let uiLanguage: string | null = null;
let labels: Partial<typeof en> = {};

/**
 * The questions that ask the user to allow something: switching to the beta channel or back
 * to an older version, recent files. Their text is the shell's own, in English or German,
 * whatever labels the page sent: the page that asks never words the question.
 */
const CONSENT_KEY = /^(updateBeta|updateOlder|recentAsk)/;

/** Keeps what fits: a known key with text, of a sane length, no function replaced and no question that asks for consent. */
export function cleanLabels(raw: unknown): Record<string, string> {
  const out: Record<string, string> = {};
  if (!raw || typeof raw !== 'object') return out;
  for (const [key, value] of Object.entries(raw as Record<string, unknown>)) {
    if (!LABEL_KEY.test(key) || CONSENT_KEY.test(key) || typeof value !== 'string' || !value.trim() || value.length > 300) continue;
    if (typeof (en as Record<string, unknown>)[key] === 'string' && labelKeepsPlaceholders(key, value)) out[key] = value;
  }
  return out;
}

/**
 * The webmail's language, once it has said, with its translations of the menus and
 * dialogs. Until then the OS's language, for what shows in early start-up: English
 * or German, built in.
 */
export function setUiLanguage(language: string, translated?: unknown): void {
  uiLanguage = language;
  labels = cleanLabels(translated) as Partial<typeof en>;
  for (const listener of languageListeners) listener();
}

const languageListeners = new Set<() => void>();

/** The tray and anything else built once hear when the text changed. Returns the unsubscribe. */
export function onUiLanguage(listener: () => void): () => void {
  languageListeners.add(listener);
  return () => languageListeners.delete(listener);
}

/** The line about mail waiting at quit. */
export function unsentDetail(text: Pick<typeof en, 'unsentOne' | 'unsentMany'>, count: number): string {
  return count === 1 ? text.unsentOne : text.unsentMany.replaceAll('{count}', String(count));
}

/** Plain text with {name} placeholders, so the webmail can translate it (labels). */
export function fill(text: string, values: Record<string, string>): string {
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => values[name] ?? whole);
}

/** The language the keystore's questions go by (keystore-strings.ts). */
export function uiLanguageNow(): string {
  return uiLanguage ?? app.getLocale();
}

export function strings(): typeof en {
  const built = (uiLanguage ?? app.getLocale()).toLowerCase().startsWith('de') ? de : en;
  return { ...built, ...labels };
}
